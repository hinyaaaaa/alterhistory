// v2.1.0: 原因リンク・君主と継承・国の連続性
import { buildSyntheticMapText } from "./helpers/synth-map.mjs";
import { loadFromBytes } from "../js/io/loader.js";
import { createRequire } from "node:module";
import { planChangeMonarch, monarchRecord, lineageOf, attachCauses, causeChain, consequences, eventKey } from "../js/core/edit/lineage.js";
import { buildTimeline } from "../js/io/chronicle.js";
import { listHistory } from "../js/core/edit/history-log.js";
let failed = 0;
const check = (l, ok, x = "") => { console.log(`  ${ok ? "OK  " : "FAIL"} ${l}${x ? "  " + x : ""}`); if (!ok) failed++; };
const D = createRequire(import.meta.url)("../js/vendor/delaunator.min.js");
const map = (await loadFromBytes(new TextEncoder().encode(buildSyntheticMapText({ seed: 7 }).text), D)).map;
const st = { map }; const A = map.pack.states.find((s) => s && s.i > 0 && !s.removed).i;
console.log("=== 君主と継承 ===");
check("初めは君主の記録なし", monarchRecord(map, A).current === null);
const c1 = planChangeMonarch(map, A, { reason: "death", title: "王", name: "アルド", stability: "stable", date: { year: 5, month: 2 } });
check("確定するまで何も残らない", !map.ext?.data?.monarchs);
c1.apply(st);
check("君主ができる（名前・称号・即位の理由）", monarchRecord(map, A).current.name === "アルド" && monarchRecord(map, A).current.reason === "death");
const c2 = planChangeMonarch(map, A, { reason: "usurpation", title: "皇帝", stability: "chaos", date: { year: 8, month: 1 } }); c2.apply(st);
const r = monarchRecord(map, A);
check("歴代に前の君主が入り、名前は自動（第N代）", r.history.length === 1 && r.history[0].until.year === 8 && r.current.name === "第2代皇帝");
check("年表に「〇〇が死去し、△△が即位」の形で1件", listHistory(map).at(-1).title.includes("が倒され、皇帝第2代皇帝が即位") && listHistory(map).filter((h) => h.type === "succession").length === 2);
let err = ""; try { planChangeMonarch(map, A, { reason: "x" }); } catch (e) { err = e.message; } check("不正な理由は拒否", !!err);
c2.revert(st); c1.revert(st);
check("Undo で君主も年表も戻る", !map.ext.data.monarchs && !listHistory(map).some((h) => h.type === "succession"));
c1.apply(st); c2.apply(st);
console.log("=== 原因リンク ===");
const tl = buildTimeline(map);
const s2 = tl.find((e) => e.type === "succession" && e.year === 8);
check("継承の混乱が、あとの反乱のきっかけとして自動で付く", (() => { const t2 = attachCauses([{ ...s2 }, { type: "rebellion", year: 9, month: 1, title: "反乱", stateIds: [A], detail: "" }]); return t2[1].causeKey === eventKey(s2) && t2[1].causeText === `${s2.title}を受けて`; })());
check("安定した継承は、きっかけにならない", (() => { const s1 = tl.find((e) => e.year === 5); const t2 = attachCauses([{ ...s1 }, { type: "rebellion", year: 6, month: 1, title: "反乱", stateIds: [A] }]); return !t2[1].causeKey; })());
check("離れすぎた出来事は、きっかけにならない", (() => { const t2 = attachCauses([{ ...s2 }, { type: "rebellion", year: 40, month: 1, title: "反乱", stateIds: [A] }]); return !t2[1].causeKey; })());
const chain = [{ type: "plague", year: 1, month: 1, title: "疫病", stateIds: [A] }, { type: "rebellion", year: 2, month: 1, title: "反乱", stateIds: [A] }, { type: "independence", year: 3, month: 1, title: "独立", stateIds: [A] }];
attachCauses(chain);
check("経緯をさかのぼれる（疫病→反乱→独立）", causeChain(chain, chain[2]).map((e) => e.title).join() === "疫病,反乱" && consequences(chain, chain[0])[0].title === "反乱");
check("cause の無い古い記録でも壊れない", attachCauses([{ type: "era", year: 1, month: 1, title: "x", stateIds: [] }]).length === 1);
console.log("=== 国の連続性 ===");
const B = map.pack.states.find((s) => s && s.i > 0 && !s.removed && s.i !== A).i;
map.pack.states[B].parentState = A;
check("分離で、前身と後継が互いに見える", lineageOf(map, B).predecessors[0].id === A && lineageOf(map, A).successors.some((x) => x.id === B));
map.ext.data.historyLog.push({ year: 9, month: 1, type: "merge", title: "統合", fromState: B, fromName: "B国", toState: A, toName: "A国" });
map.ext.data.historyLog.push({ year: 10, month: 1, type: "rename-state", title: "改名", ref: { kind: "state", id: A, from: "旧A", to: "新A" } });
const la = lineageOf(map, A);
check("統合の前身・国名の変遷が出る", la.predecessors.some((x) => x.how === "統合") && la.names[0].to === "新A");
console.log(failed ? `\n${failed} 件失敗` : "\n全て成功"); process.exit(failed ? 1 : 0);
