// v2.2.0: 世界情報の詳細化（E）・国史の書き出し（F）
import { buildSyntheticMapText } from "./helpers/synth-map.mjs";
import { loadFromBytes } from "../js/io/loader.js";
import { createRequire } from "node:module";
import { planSetWorldInfo, tagLabels, epithet, STATE_TAGS, RESOURCES } from "../js/core/edit/world-info.js";
import { planChangeMonarch } from "../js/core/edit/lineage.js";
import { buildStateHistory } from "../js/io/state-history.js";
import { describeTarget } from "../js/ui/hover-connector.js";
import { serializeNativeJson, parseNativeJson } from "../js/io/native-map.js";
let failed = 0;
const check = (l, ok, x = "") => { console.log(`  ${ok ? "OK  " : "FAIL"} ${l}${x ? "  " + x : ""}`); if (!ok) failed++; };
const D = createRequire(import.meta.url)("../js/vendor/delaunator.min.js");
const map = (await loadFromBytes(new TextEncoder().encode(buildSyntheticMapText({ seed: 7 }).text), D)).map;
const st = { map }; const S = map.pack.states.find((s) => s && s.i > 0 && !s.removed);
console.log("=== 世界情報（すべて選択式） ===");
check("特色は7種類（海洋国家・内陸国・遊牧・商業・軍事・学術・宗教国家）", STATE_TAGS.length === 7 && RESOURCES.length === 5);
const c = planSetWorldInfo(map, "state", S.i, { tags: ["maritime", "commerce"] }); c.apply(st);
check("国の特色を複数選べる・Undo で戻る", tagLabels(S).join() === "海洋国家,商業" && (c.revert(st), !S.tags?.length));
c.apply(st);
const B = map.pack.burgs.find((b) => b && b.i > 0 && !b.removed), P = map.pack.provinces.find((p) => p && p.i > 0 && !p.removed);
planSetWorldInfo(map, "burg", B.i, { kind: "trade", resources: ["salt", "iron"] }).apply(st);
planSetWorldInfo(map, "province", P.i, { title: "march", resources: ["timber"] }).apply(st);
check("都市の種類・資源、属州の称号・資源を付けられる", B.kind === "trade" && B.resources.length === 2 && P.title === "march" && P.resources[0] === "timber");
let e1 = ""; try { planSetWorldInfo(map, "state", S.i, { tags: ["nope"] }); } catch (e) { e1 = e.message; }
check("未知の選択肢は拒否される（自由入力はできない）", !!e1 && planSetWorldInfo(map, "state", S.i, { tags: ["maritime", "commerce"] }) === null);
check("説明文のテンプレートで使える（「海洋国家の」）", epithet(S) === "海洋国家の");
const mc = planChangeMonarch(map, S.i, { reason: "death", title: "王", name: "アルド" }); mc.apply(st);
check("年表の文にも特色が入る", map.ext.data.historyLog.at(-1).title.startsWith("海洋国家の"));
const cell = map.pack.cells.state.findIndex((s, i) => s === S.i && map.pack.cells.burg[i] === 0 && map.pack.cells.biome[i] !== 0);
const tg = describeTarget(map, cell);
check("ホバーカードに特色が出る", tg.kind === "state" && tg.rows.some(([a, b]) => a === "特色" && b.includes("海洋国家")));
const bt = describeTarget(map, B.cell);
check("都市のカードに種類・特産が出る", bt.rows.some(([a, b]) => a === "種類" && b === "交易都市") && bt.rows.some(([a]) => a === "特産"));
const back = parseNativeJson(serializeNativeJson(map)).map;
check("保存→読み込みで残る（旧形式のファイルには無くても開ける）", back.pack.states[S.i].tags.length === 2 && back.pack.burgs[B.i].kind === "trade" && back.pack.provinces[P.i].title === "march");
console.log("=== 国史の書き出し（Markdown） ===");
const md = buildStateHistory(map, S.i);
check("題名・君主・国名の変遷と系譜・主な出来事・原因の流れがある", ["の歴史", "## 君主", "## 国名の変遷と系譜", "## 主な出来事", "## 原因の流れ"].every((t) => md.includes(t)));
check("君主の一覧（B）と特色の文が入る", md.includes("王アルド") && md.includes("海洋国家・商業の"));
check("期間で絞れる（範囲外の出来事は入らない）", md.includes("が即位") && !buildStateHistory(map, S.i, { from: 500, to: 600 }).includes("が即位"));
let e2 = ""; try { buildStateHistory(map, 9999); } catch (e) { e2 = e.message; } check("存在しない国は拒否", !!e2);
console.log(failed ? `\n${failed} 件失敗` : "\n全て成功"); process.exit(failed ? 1 : 0);
