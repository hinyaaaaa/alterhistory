import { COMPACT, drainQueue, sweepSlow } from "./compaction-queue.js";
export { COMPACT };
/** 毎月の整理（キューの消化）。ctx.tx があれば、書き込みは月次トランザクションの journal を通る */
export function stepCompact(ctx) {
  const { civ } = ctx; if (!civ.options?.wcde) return;
  drainQueue(ctx); sweepSlow(ctx);
}
